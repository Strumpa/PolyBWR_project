import numpy as np

def check_lists(BUlist, SSHlist, COMPOlist):
    """
    Check that all points in SSH list are in BU list and that all points in COMPO list are in BU list.
    Check that all lists are in ascending order.
    """
    # Check that all points in SSH list are in BU list
    ssh_list_except_last_point = SSHlist[:-1]
    ssh_points_not_in_BU = [point for point in ssh_list_except_last_point if point not in BUlist]
    if ssh_points_not_in_BU:
        print(f"SSH points not in BU list: {ssh_points_not_in_BU}")
        return False
    # Check that all points in COMPO list are in BU list
    compo_points_not_in_BU = [point for point in COMPOlist if point not in BUlist]
    if compo_points_not_in_BU:
        print(f"COMPO points not in BU list: {compo_points_not_in_BU}")
        return False
    # Check that all lists are in ascending order
    if not (BUlist == sorted(BUlist)):
        print("BU list is not in ascending order")
        return False
    if not (SSHlist == sorted(SSHlist)):
        print("SSH list is not in ascending order")
        return False
    if not (COMPOlist == sorted(COMPOlist)):
        print("COMPO list is not in ascending order")
        return False
    return True

